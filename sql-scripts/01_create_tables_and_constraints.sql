/*TABEL 1*/ 
CREATE TABLE CLIENTI ( 
ID_CLIENT         NUMBER GENERATED BY DEFAULT AS IDENTITY, 
NUME              VARCHAR2(50)  NOT NULL, 
PRENUME           VARCHAR2(50)  NOT NULL, 
EMAIL             VARCHAR2(120) NOT NULL, 
TELEFON           
VARCHAR2(20), 
DATA_INREGISTRARE DATE DEFAULT SYSDATE NOT NULL, 
ORAS      
        VARCHAR2(60), 
ADRESA            VARCHAR2(200), 
CONSTRAINT pk_id_client PRIMARY KEY (ID_CLIENT), 
CONSTRAINT uq_email_clienti UNIQUE (EMAIL) 
); 
/*TABEL 2*/ 
CREATE TABLE CATEGORII ( 
ID_CATEGORIE NUMBER GENERATED BY DEFAULT AS IDENTITY, 
ID_PARINTE   NUMBER NULL, 
DENUMIRE     VARCHAR2(80) NOT NULL, 
CONSTRAINT pk_id_categorie PRIMARY KEY (ID_CATEGORIE), 
CONSTRAINT fk_id_parinte 
FOREIGN KEY (ID_PARINTE) REFERENCES CATEGORII(ID_CATEGORIE), 
CONSTRAINT uq_denumire_categorii UNIQUE (DENUMIRE) 
); 
/*TABEL 3*/ 
CREATE TABLE PRODUSE ( 
ID_PRODUS    NUMBER GENERATED BY DEFAULT AS IDENTITY, 
ID_CATEGORIE NUMBER NOT NULL, 
DENUMIRE     VARCHAR2(120) NOT NULL, 
BRAND        VARCHAR2(80), 
DESCRIERE    VARCHAR2(4000), 
ACTIV        CHAR(1) DEFAULT 'Y' NOT NULL, 
CONSTRAINT pk_id_produs PRIMARY KEY (ID_PRODUS), 
CONSTRAINT fk_produse_categorii 
FOREIGN KEY (ID_CATEGORIE) REFERENCES CATEGORII(ID_CATEGORIE), 
CONSTRAINT check_produse_active CHECK (ACTIV IN ('Y','N')) 
); 
/*TABEL 4*/ 
CREATE TABLE VARIANTE_PRODUS ( 
ID_VARIANTA NUMBER GENERATED BY DEFAULT AS IDENTITY, 
ID_PRODUS   NUMBER NOT NULL, 
MARIME      VARCHAR2(10) NOT NULL, 
CULOARE     VARCHAR2(30) NOT NULL, 
COD_PRODUS_ALES     VARCHAR2(40) NOT NULL, 
PRET_LISTA  NUMBER(10,2) NOT NULL, 
CONSTRAINT pk_variante_produs PRIMARY KEY (ID_VARIANTA), 
CONSTRAINT fk_variante_produs_produse 
FOREIGN KEY (ID_PRODUS) REFERENCES PRODUSE(ID_PRODUS), 
CONSTRAINT uq_cod_produs_ales UNIQUE (COD_PRODUS_ALES), 
CONSTRAINT ck_variante_pret CHECK (PRET_LISTA > 0) 
); 
/*TABEL 5*/ 
CREATE TABLE STOCURI ( 
ID_STOC
              NUMBER GENERATED BY DEFAULT AS IDENTITY, 
ID_VARIANTA          
NUMBER NOT NULL, 
CANTITATE_DISPONIBILA NUMBER DEFAULT 0 NOT NULL, 
PRAG_MINIM           
NUMBER DEFAULT 0 NOT NULL, 
ULTIMA_ACTUALIZARE   DATE DEFAULT SYSDATE NOT NULL, 
CONSTRAINT pk_id_stoc PRIMARY KEY (ID_STOC), 
CONSTRAINT fk_stocuri_variante 
FOREIGN KEY (ID_VARIANTA) REFERENCES 
VARIANTE_PRODUS(ID_VARIANTA), 
CONSTRAINT uq_stocuri_varianta UNIQUE (ID_VARIANTA), 
CONSTRAINT ck_stocuri_cantitate CHECK (CANTITATE_DISPONIBILA >= 0), 
CONSTRAINT ck_stocuri_prag CHECK (PRAG_MINIM >= 0) 
);  
/*TABEL 6*/ 
CREATE TABLE COMENZI ( 
ID_COMANDA      
NUMBER GENERATED BY DEFAULT AS IDENTITY, 
ID_CLIENT       NUMBER NOT NULL, 
DATA_COMANDA    DATE DEFAULT SYSDATE NOT NULL, 
STATUS_COMANDA  VARCHAR2(20) DEFAULT 'NOUA' NOT NULL, 
TOTAL_COMANDA   NUMBER(12,2) DEFAULT 0 NOT NULL, 
ADRESA_LIVRARE  VARCHAR2(200) NOT NULL, 
CONSTRAINT pk_comenzi PRIMARY KEY (ID_COMANDA), 
CONSTRAINT fk_comenzi_clienti 
FOREIGN KEY (ID_CLIENT) REFERENCES CLIENTI(ID_CLIENT), 
CONSTRAINT ck_comenzi_status CHECK (STATUS_COMANDA IN 
('NOUA','PLATITA','LIVRATA','ANULATA','RETURNATA')), 
CONSTRAINT ck_comenzi_total CHECK (TOTAL_COMANDA >= 0) 
); 
/*TABEL 7*/  
CREATE TABLE PLATI ( 
ID_PLATA     NUMBER GENERATED BY DEFAULT AS IDENTITY, 
ID_COMANDA   NUMBER NOT NULL, 
DATA_PLATA   DATE DEFAULT SYSDATE NOT NULL, 
METODA       VARCHAR2(20) NOT NULL, 
SUMA
         NUMBER(12,2) NOT NULL, 
STATUS_PLATA VARCHAR2(20) DEFAULT 'INITIATA' NOT NULL, 
CONSTRAINT pk_plati PRIMARY KEY (ID_PLATA), 
CONSTRAINT fk_plati_comenzi 
FOREIGN KEY (ID_COMANDA) REFERENCES COMENZI(ID_COMANDA), 
CONSTRAINT ck_plati_metoda CHECK (METODA IN 
('CARD','RAMBURS','TRANSFER')), 
CONSTRAINT ck_plati_status CHECK (STATUS_PLATA IN 
('INITIATA','CONFIRMATA','ESUATA','REFUND')), 
CONSTRAINT ck_plati_suma CHECK (SUMA > 0) 
); 
